export function buildNaviPlatformKnowledge(pageId, businessTab = "") {
  const page = PAGE_MAP[pageId] || PAGE_MAP.homePage;
  const lines = [
    "نقشه مرجع پلتفرم NAVA (اطلاعات ساختاری معتبر از رابط و قابلیت‌های پیاده‌سازی‌شده):",
    "قاعده: نام‌ها و قابلیت‌های زیر را دقیق بشناس. بین قابلیت فعال، صفحه بریف/درحال‌توسعه و قابلیت آینده تفاوت بگذار. چیزی را که صریحاً فعال معرفی نشده، انجام‌شده یا متصل‌شده جلوه نده.",
    "",
    "بخش‌های اصلی سایت:"
  ];
  for (const [id, item] of Object.entries(PAGE_MAP)) {
    lines.push("- " + item.name + " [" + id + "]");
    lines.push("  کاربرد: " + item.purpose);
    for (const capability of item.capabilities) lines.push("  • " + capability);
    if (item.tabs) {
      lines.push("  زیرتب‌های ابزارهای کسب‌وکار:");
      for (const [tabId, description] of Object.entries(item.tabs)) {
        lines.push("  - " + tabId + ": " + description);
      }
    }
  }
  lines.push("", "تب‌های داخلی پنل NAVI:");
  for (const [id, description] of Object.entries(NAVI_WORKSPACE_MAP)) {
    lines.push("- " + id + ": " + description);
  }
  lines.push("", "صفحه فعال همین درخواست:");
  lines.push("- " + page.name + " [" + pageId + "]");
  lines.push("- کاربرد: " + page.purpose);
  if (pageId === "bizPage") {
    const tabDescription = page.tabs?.[businessTab] || "";
    lines.push("- زیرتب فعال: " + (tabDescription || "مشخص نیست؛ در صورت نیاز نام زیرتب را از کاربر بپرس."));
    lines.push("- هنگام پاسخ درباره بخش کسب‌وکار، تفاوت پیش‌نویس سفارش و فروش تأییدشده، کاتالوگ و موجودی، مشتری و سفارش، و تراکنش واقعی را رعایت کن.");
  }
  lines.push("", "اگر کاربر درباره تب‌ها پرسید، نام تب‌ها را از همین نقشه بیان کن. اگر درباره جزئیات داده‌های واقعی پرونده پرسید، فقط از business financial context یا داده‌های موجود استفاده کن؛ نقشه قابلیت‌ها جایگزین داده واقعی حساب نیست.");
  return lines.join("\n");
}
